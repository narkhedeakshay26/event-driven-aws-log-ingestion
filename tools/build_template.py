#!/usr/bin/env python3
"""Embed lambda/bucket_manager.py into the CloudFormation template.

  python3 tools/build_template.py          # writes cloudformation/onboarding-stack.yaml
  python3 tools/build_template.py --check  # exit 1 if the committed template is stale

Comments and docstrings are stripped so the code fits CloudFormation's
4096-character limit for inline Lambda source.
"""
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "lambda" / "bucket_manager.py"
TEMPLATE_SRC = ROOT / "cloudformation" / "onboarding-stack.src.yaml"
OUT = ROOT / "cloudformation" / "onboarding-stack.yaml"
LIMIT = 4096
MARKER = "__MANAGER_CODE__"


def minify(code: str) -> str:
    tree = ast.parse(code)
    for node in ast.walk(tree):
        body = getattr(node, "body", None)
        if isinstance(body, list) and body and isinstance(body[0], ast.Expr) \
                and isinstance(getattr(body[0], "value", None), ast.Constant) \
                and isinstance(body[0].value.value, str):
            node.body = body[1:] or [ast.Pass()]
    lines = ast.unparse(tree).splitlines()
    # ast.unparse emits 4-space indents and single-line strings, so shrinking each
    # indent level to one space is safe and saves ~20% of the budget.
    out = []
    for l in lines:
        n = len(l) - len(l.lstrip(" "))
        out.append(" " * (n // 4) + l.lstrip(" "))
    return "\n".join(out) + "\n"


def render() -> str:
    code = minify(SRC.read_text())
    # Same-type quotes nested in an f-string only parse on Python 3.12+; keep it portable.
    nested = [l for l in code.splitlines() if re.search(r"f'[^']*\{[^}]*'|f\"[^\"]*\{[^}]*\"", l)]
    if nested:
        sys.exit("rewrite without string literals inside f-strings:\n" + "\n".join(nested))
    if len(code) > LIMIT:
        sys.exit(f"inline Lambda code is {len(code)} chars, over the {LIMIT} limit")
    template = TEMPLATE_SRC.read_text()
    line = next(l for l in template.splitlines() if MARKER in l)
    indent = line[: line.index(MARKER)]
    block = "\n".join((indent + l) if l else "" for l in code.rstrip("\n").splitlines())
    header = "# GENERATED by tools/build_template.py from onboarding-stack.src.yaml + lambda/bucket_manager.py. Do not edit.\n"
    return header + template.replace(line, block), len(code)


if __name__ == "__main__":
    text, size = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("cloudformation/onboarding-stack.yaml is stale: run tools/build_template.py")
        print("template up to date")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)} (inline code {size}/{LIMIT} chars)")
