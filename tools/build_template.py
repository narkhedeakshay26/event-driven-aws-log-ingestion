#!/usr/bin/env python3
"""Build the CloudFormation template from its source plus the Lambda code.

  python3 tools/build_template.py                        # generic template, committed to git
  python3 tools/build_template.py --trusted-principal arn:aws:iam::111122223333:role/log-ingest-consumer \
      --out dist/onboarding-stack.yaml                   # your hosted copy: principal baked in
  python3 tools/build_template.py --check                # exit 1 if the committed template is stale

The Lambda source is embedded as-is (CloudFormation allows inline code up to 4 MB),
so the template the customer deploys contains the exact, readable code in lambda/.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "lambda" / "bucket_manager.py"
TEMPLATE_SRC = ROOT / "cloudformation" / "onboarding-stack.src.yaml"
OUT = ROOT / "cloudformation" / "onboarding-stack.yaml"
LIMIT = 4 * 1024 * 1024
CODE_MARKER = "__MANAGER_CODE__"
PRINCIPAL_MARKER = "__TRUSTED_PRINCIPAL__"


def render(trusted_principal=""):
    code = SRC.read_text()
    if len(code.encode()) > LIMIT:
        sys.exit(f"inline Lambda code is {len(code.encode())} bytes, over CloudFormation's 4 MB limit")
    template = TEMPLATE_SRC.read_text()
    line = next(l for l in template.splitlines() if CODE_MARKER in l)
    indent = line[: line.index(CODE_MARKER)]
    block = "\n".join((indent + l) if l.strip() else "" for l in code.rstrip("\n").splitlines())
    header = ("# GENERATED by tools/build_template.py from onboarding-stack.src.yaml + "
              "lambda/bucket_manager.py. Do not edit.\n")
    text = header + template.replace(line, block).replace(PRINCIPAL_MARKER, trusted_principal)
    return text, len(code.encode())


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--trusted-principal", default="",
                    help="default for TrustedPrincipalArn in the built template")
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text, size = render(a.trusted_principal)
    if a.check:
        if not OUT.exists() or OUT.read_text() != render()[0]:
            sys.exit("cloudformation/onboarding-stack.yaml is stale: run tools/build_template.py")
        print("template up to date")
        return
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"wrote {out} (inline code {size:,} bytes)")


if __name__ == "__main__":
    main()
